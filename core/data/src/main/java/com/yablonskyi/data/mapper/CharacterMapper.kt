package com.yablonskyi.data.mapper

import com.yablonskyi.data.entity.CharacterEntity
import com.yablonskyi.model.character.Character

fun CharacterEntity.toModel() = Character(
    id = id,
    name = name,
    level = level,
    imagePath = imagePath,
    currentHp = currentHp,
    maxHp = maxHp,
    tempHp = tempHp,
    hitDice = hitDice,
    charClass = charClass,
    subClass = subClass,
    race = race,
    speed = speed,
    armorClass = armorClass,
    shield = shield,
    coins = coins,
    initiativeMiscBonus = initiativeMiscBonus,
    proficiencies = proficiencies,
    traits = traits,
    feats = feats,
    inventory = inventory,
    backstory = backstory,
    notes = notes,
    spellSettings = spellSettings.toModel(),
    abilityBlock = abilityBlock.toModel(),
    skillProficiencies = skillProficiencies,
    savingThrowProficiencies = savingThrowProficiencies,
    passivePerceptionBonus = passivePerceptionBonus,
    hasJackOfAllTrades = hasJackOfAllTrades,
)

fun Character.toEntity() = CharacterEntity(
    id = id,
